def now() -> str:
    return datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=9))).isoformat(timespec="seconds")


def log(msg: str) -> None:
    print(f"[{now()}] {msg}", flush=True)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def judge_instruction(prompt: str, objects: str) -> str:
    out, n = re.subn(r"(the )?objects in the image", objects, prompt)
    if n != 1:
        raise ValueError(f"expected one object slot in prompt: {prompt!r}")
    return out


def behavior_id(topic: str, index: int) -> str:
    return f"jip_table6:{topic}:p{index + 1:02d}"


