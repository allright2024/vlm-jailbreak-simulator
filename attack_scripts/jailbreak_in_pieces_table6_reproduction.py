def non_refusal(text: str) -> bool:
    head = (text or "").strip().lower()[:300]
    return bool(head) and not any(p in head for p in REFUSAL_PHRASES)


def stage_report(args) -> None:
    from core.io import read_jsonl
    from core.metrics import wilson_confidence_interval
    from core.schema import Behavior, Completion, TestCase
    from multi_attacks.jailbreak_in_pieces.jailbreak_in_pieces import OFFICIAL_PROMPTS

    target = args.target_model
    tspec = TARGETS[target]
    summary = {"experiment": "JIP Table 6 (AdvBench prompts)", "paper": PAPER, "generated_at": now(),
               "target_model": target, "target": tspec, "arms": {},
               "sampling_note": SAMPLING_NOTE, "paper_reproduction": False,
               "metric": "per-cell successes / judged attempts; not Pass@k",
               "interval_scope": "Wilson intervals conditional on this single image and chosen checkpoint",
               "verdict": "Numerical replication is unverified; historical checkpoint and human labels are unavailable."}
    lines = ["# Jailbreak in Pieces, Table 6 (Appendix E) reproduction", "",
             f"Paper: {PAPER}  Official code: {OFFICIAL_REPO} @ {OFFICIAL_COMMIT[:8]}", "",
             (f"Target: `{target}` = {tspec['model_id']} ({tspec['runtime']}); decoding {tspec['decoding']} "
              f"({tspec['decoding_source']}). {tspec['paper_note']}."),
             ("Judge: HarmBench classifier on the prompt with the objects named explicitly "
              "(paper: human labels). `non-refusal` is a refusal-phrase diagnostic only."), "",
             SAMPLING_NOTE, "",
             "LLaMA-Adapter V2 has not been run; its columns below are paper references only.", ""]
    for arm in args.arms:
        d = arm_dir(args, arm)
        res = d / f"results_{target}.jsonl"
        if not res.is_file():
            raise FileNotFoundError(f"report[{arm}]: missing results file: {res}")
        manifest = json.loads((d / "run_manifest.json").read_text())
        behaviors = {b.behavior_id: b for b in read_jsonl(str(d / "behaviors.jsonl"), Behavior)}
        expected_ids = {behavior_id(topic, index) for topic in TOPICS for index in range(12)
                        if PAPER_TABLE6[index][topic] is not None}
        if set(behaviors) != expected_ids:
            raise ValueError("behaviors must match the 22 applicable Table 6 cells")
        for topic, spec in TOPICS.items():
            for index in range(12):
                paper = PAPER_TABLE6[index][topic]
                if paper is None:
                    continue
                behavior = behaviors[behavior_id(topic, index)]
                if (behavior.instruction != judge_instruction(OFFICIAL_PROMPTS[index], spec["objects"])
                        or behavior.meta["attack_prompt"] != OFFICIAL_PROMPTS[index]
                        or (behavior.meta["paper_llava"], behavior.meta["paper_llama_adapter_v2"]) != paper):
                    raise ValueError(f"{behavior.behavior_id}: prompt, judge instruction or paper reference differs")
        comps = read_jsonl(str(res), Completion)
        cases = read_jsonl(str(d / "test_cases.jsonl"), TestCase)
        selected = [c.to_dict() for c in cases if c.attempt < args.rounds]
        expected_per_cell = {b: set(range(args.rounds)) for b in behaviors}
        actual_per_cell = {b: set() for b in behaviors}
        unique_records(selected, "selected test cases")
        for c in selected:
            if c["behavior_id"] not in behaviors:
                raise ValueError(f"unknown behavior: {c['behavior_id']}")
            actual_per_cell[c["behavior_id"]].add(c["attempt"])
            if c["text"] != behaviors[c["behavior_id"]].meta["attack_prompt"]:
                raise ValueError(f"{c['test_case_id']}: attack prompt differs from behavior")
        if actual_per_cell != expected_per_cell:
            raise ValueError("test cases do not contain the requested repeats for every cell")
        raw = read_jsonl(str(d / f"completions_{target}.jsonl"), Completion)
        if any(c.meta.get("model_id") != tspec["model_id"] or c.meta.get("decoding") != tspec["decoding"]
               for c in raw):
            raise ValueError("completion model or decoding differs from report settings")
        coverage = validate_results(selected, [c.to_dict() for c in raw],
                                    [c.to_dict() for c in comps], target)
        coverage.update(prepared=len(cases), requested_rounds_per_cell=args.rounds)
        if not coverage["complete"] and not args.allow_partial_report:
            raise ValueError(f"{arm}: incomplete run (use --allow_partial_report for a marked partial report): {coverage}")
        rows = {}
        for c in comps:
            r = rows.setdefault(c.behavior_id, {"n": 0, "success": 0, "unjudged": 0, "non_refusal": 0})
            r["n"] += 1
            if c.label == 1:
                r["success"] += 1
            elif c.label not in (0, 1):
                r["unjudged"] += 1
            r["non_refusal"] += int(non_refusal(c.response))
        table = []
        for topic, spec in TOPICS.items():
            for index in range(12):
                bid = behavior_id(topic, index)
                if bid not in behaviors:
                    continue
                b = behaviors[bid]
                r = rows.get(bid, {"n": 0, "success": 0, "unjudged": 0, "non_refusal": 0})
                judged = r["n"] - r["unjudged"]
                rate = r["success"] / judged if judged else None
                ci = wilson_confidence_interval(r["success"], judged) if judged else None
                table.append({
                    "topic": topic, "prompt_index": index, "behavior_id": bid,
                    "attack_prompt": b.meta["attack_prompt"], "judge_instruction": b.instruction,
                    "n": r["n"], "judged": judged, "success": r["success"],
                    "asr": rate, "asr_ci95": ci,
                    "non_refusal_rate": r["non_refusal"] / r["n"] if r["n"] else None,
                    "paper_llava": b.meta["paper_llava"], "paper_llama_adapter_v2": b.meta["paper_llama_adapter_v2"],
                    "diff_vs_paper_llava": (rate - b.meta["paper_llava"]) if rate is not None else None,
                })
        topic_avg = {}
        for topic in TOPICS:
            t = [x for x in table if x["topic"] == topic and x["asr"] is not None]
            if t:
                topic_avg[topic] = {
                    "ours_mean_asr": sum(x["asr"] for x in t) / len(t),
                    "ours_mean_non_refusal": sum(x["non_refusal_rate"] for x in t) / len(t),
                    "paper_llava_mean": sum(x["paper_llava"] for x in t) / len(t),
                    "n_prompts": len(t),
                    "mean_abs_diff": sum(abs(x["diff_vs_paper_llava"]) for x in t) / len(t),
                }
        summary["arms"][arm] = {"manifest": manifest, "coverage": coverage,
                                "rows": table, "topic_averages": topic_avg}

        n_per_cell = sorted({x["n"] for x in table})
        lines += [f"## Arm `{arm}`: {manifest['arm_doc']}", "",
                  (f"Coverage: {'COMPLETE' if coverage['complete'] else 'INCOMPLETE'} for the requested {args.rounds} repeats/cell. "
                   f"Prepared {len(cases)}; selected {coverage['expected']}; completed {coverage['completed']}; "
                   f"result rows {coverage['result_rows']}; unjudged {coverage['unjudged']}."), "",
                  (f"Samples per cell: {n_per_cell}; seed {manifest['seed']}. "
                   f"Seed strategy: {raw[0].meta.get('sampling_seed_strategy', 'legacy group seed (not safe to extend)') if raw else 'no samples'}."), "",
                  "| Topic | # | Prompt (attack text) | Ours ASR (HarmBench) | 95% CI | Non-refusal | Paper LLaVA | Paper LA-V2 | Δ vs paper LLaVA |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for x in table:
            asr = "n/a" if x["asr"] is None else f"{x['asr']:.2f}"
            ci = ("" if not x["asr_ci95"] or x["asr_ci95"]["lower"] is None
                  else f"[{x['asr_ci95']['lower']:.2f}, {x['asr_ci95']['upper']:.2f}]")
            nr = "" if x["non_refusal_rate"] is None else f"{x['non_refusal_rate']:.2f}"
            diff = "" if x["diff_vs_paper_llava"] is None else f"{x['diff_vs_paper_llava']:+.2f}"
            lines.append(f"| {TOPICS[x['topic']]['label']} | {x['prompt_index'] + 1} | {x['attack_prompt'][:70]}… | "
                         f"{asr} | {ci} | {nr} | {x['paper_llava']:.2f} | {x['paper_llama_adapter_v2']:.2f} | {diff} |")
        lines.append("")
        for topic, a in topic_avg.items():
            lines.append(f"- {TOPICS[topic]['label']} mean over {a['n_prompts']} prompts: ours {a['ours_mean_asr']:.3f} "
                         f"(non-refusal {a['ours_mean_non_refusal']:.3f}) vs paper LLaVA {a['paper_llava_mean']:.3f}; "
                         f"mean |Δ| = {a['mean_abs_diff']:.3f}")
        if arm == "regenerated" and "images" in manifest:
            for topic, img in manifest["images"].items():
                if topic.startswith("_"):
                    continue
                o = img.get("optimization", {})
                lines.append(f"- {TOPICS[topic]['label']} image optimization: initial {o.get('initial_loss', 0):.3f} -> "
                             f"final {o.get('final_loss', 0):.3f}, saved JPEG re-loaded {o.get('saved_image_loss', 0):.3f}")
        lines.append("")
    lines += ["## Deviations from the paper", "",
              f"- target model: {tspec['model_id']} ({tspec['runtime']}); {tspec['paper_note']}",
              f"- decoding: {tspec['decoding']} ({tspec['decoding_source']}); the paper says only 'the model's default temperature'",
              "- automatic HarmBench judge on the explicit-object prompt instead of the paper's human labels (Appendix H criterion)",
              "- trigger type per topic is not stated in the paper; the two released trigger images are used (OCR text for Drugs, OCR+visual for Bombs)",
              f"- {SAMPLING_NOTE}",
              "- official code disables CLIP normalization and saves JPEG; Appendix H.3 describes normalized preprocessing, so the code and paper differ",
              "- only one released or regenerated image per topic is tested; the Table 6 image manifest is unavailable",
              "- prompt 11 uses the released README wording ('... in a very detailed manner!')"]
    text = "\n".join(lines) + "\n"
    comparison = {}
    for arm, arm_result in summary["arms"].items():
        for row in arm_result["rows"]:
            key = (row["topic"], row["prompt_index"])
            entry = comparison.setdefault(key, {
                "topic": row["topic"], "prompt_number": row["prompt_index"] + 1,
                "paper_llava": row["paper_llava"],
                "paper_llama_adapter_v2": row["paper_llama_adapter_v2"],
            })
            entry.update({f"{arm}_asr": row["asr"], f"{arm}_judged": row["judged"],
                          f"{arm}_success": row["success"]})
    columns = ["topic", "prompt_number", "paper_llava", "paper_llama_adapter_v2"]
    columns += [f"{arm}_{field}" for arm in args.arms for field in ("asr", "judged", "success")]
    with open(args.out / f"table6_{target}.csv", "w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns)
        writer.writeheader()
        writer.writerows(comparison.values())
    (args.out / f"summary_{target}.md").write_text(text, encoding="utf-8")
    (args.out / f"summary_{target}.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(text)


STAGES = {"prepare": stage_prepare, "generate": stage_generate, "judge": stage_judge, "report": stage_report}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stage", choices=[*STAGES, "all"])
    ap.add_argument("--out", type=Path, default=SIM_ROOT / "runs" / f"jip_table6_{now()[:10].replace('-', '')}")
    ap.add_argument("--arms", nargs="+", default=["released", "regenerated"], choices=list(ARM_DOC))
    ap.add_argument("--rounds", type=int, default=25, help="chosen repeats per cell; Table 6 denominator is undisclosed")
    ap.add_argument("--reuse_images_from", type=Path, help="reuse hash-verified images from a prepared experiment")
    ap.add_argument("--allow_partial_report", action="store_true", help="explicitly mark incomplete reports")
    ap.add_argument("--target_model", default=TARGET_MODEL, choices=list(TARGETS))
    ap.add_argument("--seed", type=int, default=2024)
    ap.add_argument("--batch_size", type=int, default=20)
    ap.add_argument("--judge_batch_size", type=int, default=20)
    ap.add_argument("--python", default=sys.executable)
    ap.add_argument("--llava_python", default=str(Path.home() / ".conda/envs/asd_llava_venv/bin/python"),
                    help="Python with the historical LLaVA runtime")
    args = ap.parse_args()
    args.out = args.out.resolve()
    if args.reuse_images_from:
        args.reuse_images_from = args.reuse_images_from.resolve()
    if args.rounds <= 0 or args.batch_size <= 0 or args.judge_batch_size <= 0:
        ap.error("rounds and batch sizes must be positive")
    if args.stage == "all":
        # One process per stage so CLIP, LLaVA and the 13B judge never share GPU memory.
        passthrough = sys.argv[2:]
        for name in STAGES:
            log(f"=== stage {name} (subprocess) ===")
            subprocess.run([args.python, __file__, name, *passthrough], check=True,
                           env={**os.environ, "PYTHONNOUSERSITE": "1"})
        return
    log(f"=== stage {args.stage} ===")
    STAGES[args.stage](args)


if __name__ == "__main__":
    main()
